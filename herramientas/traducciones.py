def traducirRemate(evento):
    """Monta el nombre de un golpe de gracia, o devuelve None si no lo es."""
    if "KillMove" not in evento and "KillingBlow" not in evento:
        return None
    if evento == "pa_KillingBlow":
        return "Golpe de gracia"

    resto = evento.replace("pa_", "").replace("KillMove", "").replace("KillingBlow", "")

    arma = objetivo = golpe = ""
    for clave, texto in REMATE_ARMA:
        if clave in resto:
            arma = texto
            resto = resto.replace(clave, "", 1)
            break
    for clave, texto in REMATE_OBJETIVO:
        if clave in resto:
            objetivo = texto
            resto = resto.replace(clave, "", 1)
            break
    for clave, texto in REMATE_GOLPE:
        if clave in resto:
            golpe = texto
            resto = resto.replace(clave, "", 1)
            break

    # Lo que queda suele ser "Short" y una letra de variante: A, B, C...
    corto = "Short" in resto
    resto = resto.replace("Short", "")
    letra = resto.strip("_") if len(resto.strip("_")) <= 2 else ""

    partes = ["Remate"]
    if golpe:
        partes.append(": " + golpe)
    if arma:
        partes.append(" " + arma)
    if objetivo:
        partes.append(" contra " + objetivo)
    nombre = "".join(partes)
    if corto:
        nombre += " (corto)"
    if letra:
        nombre += " (" + letra + ")"
    return nombre


